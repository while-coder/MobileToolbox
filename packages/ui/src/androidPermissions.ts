export function permissionDescription(permission: string): string {
  const prefix = "android.permission."
  const description = permission.startsWith(prefix)
    ? systemPermissions[permission.slice(prefix.length)]
    : otherPermissions[permission]
  if (description) return description
  if (permission.endsWith(".DYNAMIC_RECEIVER_NOT_EXPORTED_PERMISSION")) {
    return "AndroidX 生成的应用内部广播权限，用于限制动态广播接收器的访问。"
  }
  return "本地说明表暂未收录，可能是应用或第三方 SDK 的自定义权限。"
}
